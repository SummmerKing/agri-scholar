def load_ablation_081251(path):
    with open(path, 'r') as f:
        data = json.load(f)
    results = {}
    for d in data:
        if d['status'] == 'ok':
            y = d['year']
            sr = d['season_result']
            final_reward = sr['final_reward_breakdown']['reward']
            norm_reward = final_reward / 20.09
            results[y] = {
                "yield": sr['final_yield_kg_ha'],
                "reward": norm_reward,
                "drainage": sr['final_diagnostics']['total_drainage_mm'],
                "leaching": sr['final_diagnostics']['total_leach_no3_nh4']
            }
    return results

aba_500 = load_ablation_081251(os.path.join(RESULTS, "agri_sigra_combined_20261009_081251.json"))
aba_unconstrained = load_ablation_081251(os.path.join(RESULTS, "agri_sigra_combined_20261009_112907.json"))

print(r"\subsection{Analysis of Advisory Bounding Agent Ablation Study}")
print(r"To isolate and quantify the impact of the Advisory Bounding Agent (ABA), we conducted an ablation study comparing the full Agri-SCHOLAR framework (\textbf{With ABA}) against two variations of the unconstrained numerical optimizer (Optuna).")
print(r"In the \textbf{Without ABA (Loose Bounds)} baseline, the optimizer was allowed to search without semantic bounds but had a hard ceiling per split application. In the \textbf{Without ABA (No Bounds)} baseline, all bounds were removed, allowing the agent to apply up to an infinite theoretical amount of urea per split. Both optimizer baselines were allowed up to 18 split applications per season. The goal was to determine whether a purely profit-driven numerical optimizer could discover viable management strategies through blind optimization.")
print(r"\subsubsection{The ``Reward Hacking'' Phenomenon and Qualitative Failure}")
print(r"At a surface level, the loosely bounded optimizer appeared to compete with or slightly outperform the constrained Agri-SCHOLAR agent in terms of raw mathematical yield and normalized reward. Across the 11-year simulation (2015--2025) in Mandya, this variant achieved a slightly higher Mean Yield (+153.82 kg/ha), as shown in Tables \ref{tab:ablation_yield} and \ref{tab:ablation_reward}.")
print(r"However, this purely quantitative comparison is deceptive. The shadow prices within the reward function (e.g., $S_{\mathrm{nl}}$, $S_{\mathrm{dd}}$) act as a mathematical counterbalance that makes the final \textbf{Without ABA} scores look better, masking how qualitatively poor the underlying actions actually are. When we manually inspect the simulated advisories generated by the optimizers, we observe rampant \textbf{reward hacking}. To bypass the fixed labor cost ($p_L = 350$ LCU per application), the optimizer prescribes actions that maximize the numerical reward function but are physically, biologically, and agronomically impossible to execute in reality.")
print(r"Specifically, the optimizers' recommendations frequently fell into two unfeasible extremes:")
print(r"\begin{itemize}")
print(r"\item \textbf{High-Risk Massive Single Applications (Too High):} To minimize labor costs, the optimizers frequently dumped nearly the entire season's nitrogen budget in a single application. For example, in 2019, the agent with no bounds attempted a mathematically optimal but agronomically absurd application of 6,062.2 kg/ha of Urea at planting. Even with loose bounds, dumping massive amounts of urea on emerging seedlings would cause fatal ammonia toxicity (fertilizer burn)---a biological limitation the simulator does not perfectly penalize, allowing the optimizer to cheat the system.")
print(r"\item \textbf{Agronomically Impractical Micro-Doses (Too Low):} To squeeze out marginal simulated yield gains without triggering heavy leaching penalties, the optimizer prescribed minute quantities of nitrogen that standard farm machinery cannot physically calibrate or apply evenly over a hectare. Examples include doses as small as 2--4 kg/ha.")
print(r"\end{itemize}")
print(r"\subsubsection{Environmental Degradation and Volatility}")
print(r"Because the optimizers relied on massive single-dose applications to minimize labor costs, they severely compromised environmental sustainability. The soil profile cannot retain hundreds or thousands of kilograms of nitrogen at once; consequently, heavy rain events washed the excess away.")
print(r"As shown in Tables \ref{tab:ablation_drainage} and \ref{tab:ablation_leaching}, the removal of ABA constraints resulted in dramatically worse environmental outcomes. For instance, the completely unbounded optimizer's 2019 massive dump resulted in a catastrophic 3,270.7 kg/ha of NO$_3$ leaching when subjected to actual weather, triggering a massive sustainability penalty and an overall net loss.")
print(r"Furthermore, the optimizers without ABA exhibited dangerous volatility. While they achieved mathematical highs in years like 2016, their lack of agronomic guardrails led to catastrophic failures when weather did not perfectly align with their massive single-dose bets.")
print(r"\subsubsection{Conclusion}")
print(r"The ablation study definitively demonstrates that while numerical optimization can find theoretical maxima in an agricultural simulation, those maxima are frequently detached from physical reality. The baselines without ABA achieved high theoretical yields only by proposing strategies that would fail catastrophically in a real field and resulted in extreme environmental runoff. The \textbf{Advisory Bounding Agent (ABA)} is therefore a strict requirement; it acts as a critical domain-translation layer, forcing the reinforcement learning agent to find the highest \emph{practically realizable} and environmentally responsible yield, rather than overfitting to the simulation's mathematical edge cases.")

